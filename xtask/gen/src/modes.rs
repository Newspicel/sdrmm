use std::{fmt::Write as _, path::Path};

use anyhow::{Context, Result, bail};
use sdrmm_wire::{ChannelDescriptor, DecoderFamily, HzRange, Verification};
use serde::Serialize;

pub(crate) const DOCS_PAGE: &str = "docs/operate/decoders.md";
pub(crate) const DOCS_SUBDIR: &str = "docs/operate/decoders";
pub(crate) const SITE_DATA: &str = "site/src/data/modes.json";

const BEGIN: &str = "<!-- generated by `cargo xtask codegen` from the decoder registry -->\n";
const END: &str = "<!-- end generated -->\n";

#[derive(Clone, Debug)]
struct HeadingRef {
    text: String,
    rel_file: Option<String>,
    site_slug: String,
}

/// Every decoder in the registry, by name.
pub(crate) fn decoders() -> Vec<ChannelDescriptor> {
    let mut all = sdrmm_decoder::descriptors();
    all.sort_by_key(|decoder| decoder.name.to_lowercase());
    all
}

/// The decoders page with its catalog rebuilt between the markers. Prose around it stays as
/// written.
pub(crate) fn docs_page(
    root: &Path,
    current: &str,
    decoders: &[ChannelDescriptor],
) -> Result<String> {
    let (head, rest) = current
        .split_once(BEGIN)
        .with_context(|| format!("{DOCS_PAGE} has no generated catalog marker"))?;
    let Some((_, tail)) = rest.split_once(END) else {
        bail!("{DOCS_PAGE} has no end of generated catalog marker");
    };
    let mut all_headings = page_headings(&format!("{head}{tail}"), None, "/docs/operate/decoders");
    all_headings.extend(subdir_headings(&root.join(DOCS_SUBDIR))?);
    Ok(format!(
        "{head}{BEGIN}{}{END}{tail}",
        catalog(decoders, &all_headings)
    ))
}

fn subdir_headings(dir: &Path) -> Result<Vec<HeadingRef>> {
    if !dir.is_dir() {
        return Ok(Vec::new());
    }
    let mut files = Vec::new();
    for entry in std::fs::read_dir(dir).with_context(|| format!("read {}", dir.display()))? {
        let path = entry?.path();
        if path.extension().is_some_and(|ext| ext == "md") {
            files.push(path);
        }
    }
    files.sort();
    let mut found = Vec::new();
    for path in files {
        let stem = path
            .file_stem()
            .and_then(|s| s.to_str())
            .with_context(|| format!("invalid file name {}", path.display()))?;
        let text =
            std::fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
        found.extend(page_headings(
            &text,
            Some(format!("decoders/{stem}.md")),
            &format!("/docs/operate/decoders/{stem}"),
        ));
    }
    Ok(found)
}

fn page_headings(page: &str, rel_file: Option<String>, site_slug: &str) -> Vec<HeadingRef> {
    page.lines()
        .filter_map(|line| line.strip_prefix("## "))
        .map(|text| HeadingRef {
            text: text.to_owned(),
            rel_file: rel_file.clone(),
            site_slug: site_slug.to_owned(),
        })
        .collect()
}

fn catalog(decoders: &[ChannelDescriptor], headings: &[HeadingRef]) -> String {
    let levels = levels_in(decoders);
    let mut out = String::from("| Group |");
    for level in &levels {
        let _ = write!(out, " {} |", level.label());
    }
    out.push_str("\n|---|");
    out.push_str(&"---|".repeat(levels.len()));
    out.push('\n');
    for family in families(decoders) {
        let _ = write!(out, "| {} |", family.title());
        for level in &levels {
            let names: Vec<String> = decoders
                .iter()
                .filter(|decoder| decoder.family == family && decoder.verification == *level)
                .map(|decoder| linked(&decoder.name, headings))
                .collect();
            out.push_str(&cell(&names));
        }
        out.push('\n');
    }
    out.push_str("\n| Label | Means |\n|---|---|\n");
    for level in &levels {
        let _ = writeln!(out, "| {} | {} |", level.label(), level.meaning());
    }
    out
}

fn cell(names: &[String]) -> String {
    if names.is_empty() {
        " |".to_owned()
    } else {
        format!(" {} |", names.join(", "))
    }
}

fn levels_in(decoders: &[ChannelDescriptor]) -> Vec<Verification> {
    Verification::ALL
        .into_iter()
        .filter(|level| {
            decoders
                .iter()
                .any(|decoder| decoder.verification == *level)
        })
        .collect()
}

/// Built-in families in their set order, then any a plugin brought, by name.
fn families(decoders: &[ChannelDescriptor]) -> Vec<DecoderFamily> {
    let mut added: Vec<DecoderFamily> = decoders
        .iter()
        .map(|decoder| decoder.family.clone())
        .filter(|family| !DecoderFamily::BUILT_IN.contains(family))
        .collect();
    added.sort();
    added.dedup();
    DecoderFamily::BUILT_IN
        .iter()
        .filter(|family| decoders.iter().any(|decoder| decoder.family == **family))
        .cloned()
        .chain(added)
        .collect()
}

fn match_heading<'a>(name: &str, headings: &'a [HeadingRef]) -> Option<&'a HeadingRef> {
    headings.iter().find(|heading| names(&heading.text, name))
}

/// A decoder's name, linked to the first section whose heading names it.
fn linked(name: &str, headings: &[HeadingRef]) -> String {
    match_heading(name, headings).map_or_else(
        || name.to_owned(),
        |heading| match &heading.rel_file {
            Some(file) => format!("[{name}]({file}#{})", anchor(&heading.text)),
            None => format!("[{name}](#{})", anchor(&heading.text)),
        },
    )
}

fn site_doc_href(name: &str, headings: &[HeadingRef]) -> Option<String> {
    match_heading(name, headings)
        .map(|heading| format!("{}#{}", heading.site_slug, anchor(&heading.text)))
}

fn names(heading: &str, name: &str) -> bool {
    let name = name.to_lowercase();
    heading
        .split(", ")
        .flat_map(|part| part.split(" and "))
        .map(str::to_lowercase)
        .any(|part| leads(&name, &part) || leads(&part, &name))
}

fn leads(text: &str, word: &str) -> bool {
    text.strip_prefix(word)
        .is_some_and(|rest| !rest.starts_with(char::is_alphanumeric))
}

/// GitHub / github-slugger anchor id used by Astro's markdown renderer.
fn anchor(heading: &str) -> String {
    heading
        .chars()
        .filter_map(|ch| {
            if ch.is_alphanumeric() || ch == '_' || ch == '-' {
                Some(ch.to_ascii_lowercase())
            } else if ch.is_whitespace() {
                Some('-')
            } else {
                None
            }
        })
        .collect()
}

#[derive(Serialize)]
struct SiteData {
    levels: Vec<Level>,
    families: Vec<Family>,
    modes: Vec<Mode>,
}

#[derive(Serialize)]
struct Level {
    id: Verification,
    label: &'static str,
    means: &'static str,
}

#[derive(Serialize)]
struct Family {
    id: DecoderFamily,
    title: String,
}

#[derive(Serialize)]
struct Mode {
    type_id: String,
    name: String,
    summary: String,
    family: DecoderFamily,
    verification: Verification,
    input_rate_hz: f64,
    bands: Vec<HzRange>,
    #[serde(skip_serializing_if = "Option::is_none")]
    doc: Option<String>,
}

/// What the site's modes page lists.
pub(crate) fn site_data(root: &Path, decoders: &[ChannelDescriptor]) -> Result<String> {
    let mut headings = Vec::new();
    let main_doc = root.join(DOCS_PAGE);
    if main_doc.is_file() {
        let text = std::fs::read_to_string(&main_doc)
            .with_context(|| format!("read {}", main_doc.display()))?;
        headings.extend(page_headings(&text, None, "/docs/operate/decoders"));
    }
    headings.extend(subdir_headings(&root.join(DOCS_SUBDIR))?);

    let data = SiteData {
        levels: levels_in(decoders)
            .into_iter()
            .map(|level| Level {
                id: level,
                label: level.label(),
                means: level.meaning(),
            })
            .collect(),
        families: families(decoders)
            .into_iter()
            .map(|family| Family {
                title: family.title(),
                id: family,
            })
            .collect(),
        modes: decoders
            .iter()
            .map(|decoder| mode(decoder, &headings))
            .collect(),
    };
    Ok(format!("{}\n", serde_json::to_string_pretty(&data)?))
}

fn mode(decoder: &ChannelDescriptor, headings: &[HeadingRef]) -> Mode {
    Mode {
        type_id: decoder.type_id.clone(),
        name: decoder.name.clone(),
        summary: decoder.summary.clone(),
        family: decoder.family.clone(),
        verification: decoder.verification,
        input_rate_hz: decoder.input_rate_hz,
        bands: bands(decoder),
        doc: site_doc_href(&decoder.name, headings),
    }
}

/// Where the decoder's signatures say its service is allocated, merged; empty for anywhere.
fn bands(decoder: &ChannelDescriptor) -> Vec<HzRange> {
    let mut ranges: Vec<HzRange> = decoder
        .signatures
        .iter()
        .flat_map(|signature| signature.frequencies.iter().copied())
        .collect();
    ranges.sort_by(|a, b| a.low.total_cmp(&b.low));
    let mut merged: Vec<HzRange> = Vec::with_capacity(ranges.len());
    for range in ranges {
        match merged.last_mut() {
            Some(last) if range.low <= last.high => last.high = last.high.max(range.high),
            _ => merged.push(range),
        }
    }
    merged
}

#[cfg(test)]
mod tests {
    use super::*;
    use sdrmm_wire::SignalSignature;

    fn decoder(name: &str, family: DecoderFamily, verification: Verification) -> ChannelDescriptor {
        ChannelDescriptor {
            type_id: name.to_lowercase(),
            name: name.to_owned(),
            family,
            verification,
            ..ChannelDescriptor::default()
        }
    }

    fn heading(text: &str, rel_file: Option<&str>, site_slug: &str) -> HeadingRef {
        HeadingRef {
            text: text.to_owned(),
            rel_file: rel_file.map(str::to_owned),
            site_slug: site_slug.to_owned(),
        }
    }

    #[test]
    fn a_heading_links_the_decoders_it_names() {
        let headings = [
            heading(
                "TETRA",
                Some("decoders/voice.md"),
                "/docs/operate/decoders/voice",
            ),
            heading(
                "2.4 GHz survey and Wi-Fi occupancy",
                Some("decoders/utility-iot.md"),
                "/docs/operate/decoders/utility-iot",
            ),
            heading(
                "DAB and DAB+",
                Some("decoders/broadcast-video.md"),
                "/docs/operate/decoders/broadcast-video",
            ),
        ];
        assert_eq!(
            linked("TETRA", &headings),
            "[TETRA](decoders/voice.md#tetra)"
        );
        assert_eq!(linked("Tetrapol", &headings), "Tetrapol");
        assert_eq!(
            linked("Wi-Fi occupancy", &headings),
            "[Wi-Fi occupancy](decoders/utility-iot.md#24-ghz-survey-and-wi-fi-occupancy)"
        );
        assert_eq!(
            linked("DAB / DAB+", &headings),
            "[DAB / DAB+](decoders/broadcast-video.md#dab-and-dab)"
        );
        assert_eq!(
            site_doc_href("TETRA", &headings).as_deref(),
            Some("/docs/operate/decoders/voice#tetra")
        );
    }

    #[test]
    fn the_catalog_has_a_column_per_level_in_use() {
        let decoders = [
            decoder(
                "AM",
                DecoderFamily::ANALOG_VOICE,
                Verification::OwnModulator,
            ),
            decoder("DMR", DecoderFamily::DIGITAL_VOICE, Verification::OnAir),
            decoder("Probe", DecoderFamily::new("lab"), Verification::Unverified),
        ];
        let table = catalog(&decoders, &[]);
        assert!(table.starts_with("| Group | Tested on air | Own modulator | Unverified |\n"));
        assert!(table.contains("| Analog voice | | AM | |\n"));
        assert!(table.contains("| Lab | | | Probe |\n"));
        assert!(!table.contains("Reference fixture"));
    }

    #[test]
    fn only_the_marked_catalog_is_rebuilt() {
        let tmp = tempfile::tempdir().expect("tempdir");
        let page = format!("# Decoders\n\nIntro.\n\n{BEGIN}old\n{END}\n## DMR\n\nText.\n");
        let decoders = [decoder(
            "DMR",
            DecoderFamily::DIGITAL_VOICE,
            Verification::OnAir,
        )];
        let rebuilt = docs_page(tmp.path(), &page, &decoders).expect("rebuild");
        assert!(rebuilt.starts_with("# Decoders\n\nIntro.\n\n"));
        assert!(rebuilt.contains("| Digital voice | [DMR](#dmr) |\n"));
        assert!(!rebuilt.contains("old"));
        assert!(rebuilt.ends_with("## DMR\n\nText.\n"));
        assert!(docs_page(tmp.path(), "# Decoders\n", &decoders).is_err());
    }

    #[test]
    fn bands_merge_the_signature_allocations() {
        let mut signature = SignalSignature::new("probe", &[], HzRange::new(0.0, 1.0), "test");
        signature.frequencies = vec![
            HzRange::mhz(430.0, 450.0),
            HzRange::mhz(144.0, 148.0),
            HzRange::mhz(440.0, 470.0),
        ];
        let probe = ChannelDescriptor {
            signatures: vec![signature],
            ..ChannelDescriptor::default()
        };
        assert_eq!(
            bands(&probe),
            vec![HzRange::mhz(144.0, 148.0), HzRange::mhz(430.0, 470.0)]
        );
        assert!(bands(&ChannelDescriptor::default()).is_empty());
    }

    #[test]
    fn the_site_data_lists_every_built_in_decoder() {
        sdrmm_channels::builtin::install();
        let decoders = decoders();
        let data = site_data(&crate::root(), &decoders).expect("site data");
        for decoder in &decoders {
            assert!(data.contains(&format!("\"type_id\": \"{}\"", decoder.type_id)));
        }
        assert!(!data.contains('\u{2014}'), "no em dash");
    }
}
